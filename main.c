#include <stdio.h>

int main(void)
{
    int age;

    // Ввод возраста пользователя
    printf("Введите возраст пассажира: ");
    
    // Проверяем, что пользователь ввел именно целое число
    if (scanf("%d", &age) != 1) 
    {
        printf("Ошибка ввода! Ожидалось целое число.\n");
        return 1;
    }

    // Проверка условий стоимости билета (цепочка if - else if - else)
    if (age < 0 || age > 120) 
    {
        printf("ошибочный возраст\n");
    } 
    else if (age <= 6) 
    {
        printf("билет бесплатный\n");
    } 
    else if (age <= 17) 
    {
        printf("стоимость 150 рублей\n");
    } 
    else if (age <= 59) 
    {
        printf("стоимость 300 рублей\n");
    } 
    else 
    {
        printf("стоимость 180 рублей\n");
    }

    return 0;
}
