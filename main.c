#include <stdio.h>

int main(void)
{
    /* --- Часть 1: Анализ целого числа --- */
    int number;

    printf("=== Часть 1: Анализ целого числа ===\n");
    printf("Введите целое число: ");
    if (scanf("%d", &number) != 1)
    {
        printf("Ошибка ввода! Ожидалось целое число.\n");
        return 1;
    }

    if (number > 0)
    {
        printf("Число положительное.\n");
    }
    else if (number < 0)
    {
        printf("Число отрицательное.\n");
    }
    else
    {
        printf("Число равно нулю.\n");
    }

    if (number % 2 == 0)
    {
        printf("Число чётное.\n");
    }
    else
    {
        printf("Число нечётное.\n");
    }

    /* --- Часть 2: Стоимость билета --- */
    int age;

    printf("\n=== Часть 2: Стоимость билета ===\n");
    printf("Введите возраст пассажира: ");
    if (scanf("%d", &age) != 1)
    {
        printf("Ошибка ввода! Ожидалось целое число.\n");
        return 1;
    }

    if (age < 0 || age > 120)
    {
        printf("Некорректный возраст\n");
    }
    else if (age <= 6)
    {
        printf("Билет бесплатный\n");
    }
    else if (age <= 17)
    {
        printf("Стоимость 150 рублей\n");
    }
    else if (age <= 59)
    {
        printf("Стоимость 300 рублей\n");
    }
    else
    {
        printf("Стоимость 180 рублей\n");
    }

    return 0;
}
